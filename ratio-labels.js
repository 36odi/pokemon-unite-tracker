function ratioJapaneseLabel(text){
  let s=RATIO_JAPANESE_TEXT[text]||text;
  s=s.replace(/ヒットごと|ヒット毎/g,'1ヒットあたり')
    .replace(/花ごと/g,'花1個あたり').replace(/コインマークごと/g,'コインマーク1枚あたり')
    .replace(/カウンター毎|カウンターごと/g,'カウンター1個あたり')
    .replace(/強化攻撃毎/g,'強化攻撃1回あたり').replace(/条件発動毎/g,'条件成立1回あたり')
    .replace(/炎毎|炎ごと/g,'炎1つあたり').replace(/弾ごと/g,'弾1発あたり')
    .replace(/コピーごと/g,'分身1体あたり').replace(/衝撃波毎/g,'衝撃波1回あたり').replace(/雷撃ごと/g,'雷撃1回あたり')
    .replace(/(\d+)発毎/g,'$1発ごと').replace(/(\d+)\s+ヒット/g,'$1ヒット').replace(/(\d+)\s+回/g,'$1回')
    .replace(/ダメージ：ステージ\s*(\d+)|ダメージ：第(\d+)段階/g,(_,a,b)=>`ダメージ（${a||b}段階目）`)
    .replace(/^ステージ(\d+)$/,'通常攻撃（$1段目）')
    .replace(/爆炎 レベル (\d+)/g,'爆炎（$1段階目）').replace(/(\d+) 牙マーク/g,'牙マーク$1個')
    .replace(/レベル1チャージ/g,'チャージ1段階目').replace(/第(\d+)チャージ/g,'チャージ$1段階目')
    .replace(/チャージ([0-9]+)(?![0-9～段])/g,'チャージ$1段階')
    .replace(/未チャージ/g,'ためていないとき').replace(/最大チャージ/g,'最大までためたとき')
    .replace(/チャージ済み/g,'ためたとき').replace(/近接距離|近接|長距離/g,m=>m==='長距離'?'遠距離':'近距離')
    .replace(/ファイター モード/g,'ファイターモード').replace(/1回目使用/g,'1回目の使用').replace(/2回目使用/g,'2回目の使用')
    .replace(/最初のスター/g,'最初の星').replace(/継続スター/g,'続く星')
    .replace(/\s*&\s*|＆/g,'・').replace(/\s*（\s*/g,'（').replace(/\s*）/g,'）');
  // 条件の区切りを「効果（条件・条件）」へそろえる。
  // 「効果（条件）：条件」の旧形式も同じ並びにする。
  s=s.replace(/^([^（）]+)（([^（）]+)）：(.+)$/,'$1：$2・$3');
  const colon=s.indexOf('：');
  if(colon>=0&&!s.slice(0,colon).includes('（')){
    const condition=s.slice(colon+1).replace(/（/g,'・').replace(/）/g,'').replace(/：/g,'・').trim();
    s=s.slice(0,colon)+'（'+condition+'）';
  }
  return s;
}

function ratioLabel(poke,r){
  const key=[poke,r.name.replace(/[+＋]$/,''),r.dmgType].join('|');
  const labels=RATIO_COMPONENT_LABELS[key];
  let label=RATIO_LABEL_TEXT[r.dmgType]||r.dmgType||'効果';
  if(r.dmgType==='ダメージ - 初撃'&&RATIO_SECOND_HIT[poke]?.includes(r.name.replace(/[+＋]$/,''))) label='ダメージ（2段目）';
  if(labels){
    const peers=LAB_SKILLS[poke].filter(s=>s.slot===r.slot&&s.name===r.name&&s.upg===r.upg&&s.dmgType===r.dmgType);
    const index=peers.indexOf(r);
    if(peers.length===labels.length&&index>=0) label=labels[index];
    else label+='（条件の対応を要確認）';
  }
  return ratioJapaneseLabel(label.replace(/ティックごと/g,'継続効果1回あたり').replace(/ヒット毎/g,'1ヒットあたり')
    .replace(/シールドフォーム/g,'シールドフォルム').replace(/パンチ スタイル/g,'パンチスタイル')
    .replace(/キック スタイル/g,'キックスタイル').replace(/最大 チャージ/g,'最大チャージ')
    .replace(/ - /g,'：').replace(/\(/g,'（').replace(/\)/g,'）'));
}

function ratioMoveName(poke,r){
  if(poke==='バシャーモ'&&r.name==='爆炎旋風拳')
    return ratioLabel(poke,r).startsWith('爆炎旋風脚')?'爆炎旋風脚':'爆炎旋風拳';
  if(poke==='ウーラオス'&&r.name==='漆黒の終拳'&&[
    'ダメージ (初撃)','ダメージ (ヒット during follow-up attack)','ダメージ (最終ヒット and shove)'
  ].includes(r.dmgType)) return '蒼流の舞踏';
  return r.name;
}

function ratioComponentNote(poke,r){
  if(poke==='ヌメルゴン'&&r.name.startsWith('りゅうのはどう')&&r.dmgType==='回復')
    return '回復の固定部分です。自身の減少HPに応じた回復はこの式に含まれません。';
  if(poke==='ヌメルゴン'&&r.name.startsWith('アシッドボム')&&ratioLabel(poke,r).includes('突進'))
    return '突進は2回命中します。式は1回分です。';
  return '';
}
