function ratioLabel(poke,r){
  const key=[poke,r.name.replace(/[+＋]$/,''),r.dmgType].join('|');
  const labels=RATIO_COMPONENT_LABELS[key];
  let label=RATIO_LABEL_TEXT[r.dmgType]||r.dmgType||'効果';
  if(r.dmgType==='ダメージ - 初撃'&&RATIO_SECOND_HIT[poke]?.includes(r.name.replace(/[+＋]$/,''))) label='ダメージ（2段目）';
  if(labels){
    const peers=LAB_SKILLS[poke].filter(s=>s.slot===r.slot&&s.name===r.name&&s.upg===r.upg&&s.dmgType===r.dmgType);
    const index=peers.indexOf(r);
    if(peers.length===labels.length&&index>=0) label=labels[index];
    else label+='（条件の対応を要確認）';
  }
  return label.replace(/ティックごと/g,'継続効果1回あたり').replace(/ヒット毎/g,'1ヒットあたり')
    .replace(/シールドフォーム/g,'シールドフォルム').replace(/パンチ スタイル/g,'パンチスタイル')
    .replace(/キック スタイル/g,'キックスタイル').replace(/最大 チャージ/g,'最大チャージ')
    .replace(/ - /g,'：').replace(/\(/g,'（').replace(/\)/g,'）');
}

function ratioMoveName(poke,r){
  if(poke==='バシャーモ'&&r.name==='爆炎旋風拳')
    return ratioLabel(poke,r).startsWith('爆炎旋風脚')?'爆炎旋風脚':'爆炎旋風拳';
  if(poke==='ウーラオス'&&r.name==='漆黒の終拳'&&[
    'ダメージ (初撃)','ダメージ (ヒット during follow-up attack)','ダメージ (最終ヒット and shove)'
  ].includes(r.dmgType)) return '蒼流の舞踏';
  return r.name;
}

function ratioComponentNote(poke,r){
  if(poke==='ヌメルゴン'&&r.name.startsWith('りゅうのはどう')&&r.dmgType==='回復')
    return '回復の固定部分です。自身の減少HPに応じた回復はこの式に含まれません。';
  if(poke==='ヌメルゴン'&&r.name.startsWith('アシッドボム')&&ratioLabel(poke,r).includes('突進'))
    return '突進は2回命中します。式は1回分です。';
  return '';
}
