// JSONを編集元とし、file://でも読める通常のスクリプトを生成する。
const fs=require('node:fs'),path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
function build(){
 const rules=JSON.parse(fs.readFileSync(path.join(ROOT,'data/attack-speed-rules.json'),'utf8'));
 const {profiles}=JSON.parse(fs.readFileSync(path.join(ROOT,'data/attack-speed-profiles.json'),'utf8'));
 return '// Generated by tools/build_attack_speed_data.js. Edit data/attack-speed-*.json.\nwindow.LAB_ATTACK_SPEED_DATA='+JSON.stringify({rules,profiles})+';\n';
}
if(require.main===module){
 const target=path.join(ROOT,'js/attack-speed-data.js'),source=build();
 if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==source)throw Error('速度資料を再生成してください: node tools/build_attack_speed_data.js');
  console.log('Attack speed data bundle matches both JSON sources');
 }else{fs.writeFileSync(target,source);console.log('Generated file-compatible attack speed data');}
}
module.exports={build};
